"""Build a relocatable Windows backend with pinned Python and locked dependencies.

    uv run --locked python scripts/build_windows_backend.py

Build on Windows. Output: dist/windows/<arch>/MarketPulse-backend. The future native
app can run python/python.exe -I -B -X utf8 -m marketpulse with an argument array; humans
can use marketpulse.cmd. Neither requires an installed Python or uv at runtime.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from marketpulse import __version__

ROOT = Path(__file__).resolve().parents[1]
PYTHON = "3.14.7"  # kept aligned with the Mac bundle; upgrade deliberately
ARCHES = {"x86_64": ("x86_64", "x86_64-pc-windows-msvc")}
LAUNCHER = """@echo off
setlocal DisableDelayedExpansion
"%~dp0python\\python.exe" -I -B -X utf8 -m marketpulse %*
exit /b %errorlevel%
"""


def run(*args: str | Path, **kwargs) -> subprocess.CompletedProcess:
    return subprocess.run([str(a) for a in args], check=True, **kwargs)


def build(arch: str, out: Path, work: Path) -> Path:
    """Use binary wheels only, honoring the lock's target-platform markers and hashes."""
    wheels = work / "wheel"
    run("uv", "build", "--wheel", "--no-sources", "--out-dir", wheels, cwd=ROOT)
    (wheel,) = wheels.glob("marketpulse-*.whl")
    if wheel.name.split("-")[1] != __version__:
        raise SystemExit(f"{wheel.name} doesn't match MarketPulse {__version__}.")
    key = f"cpython-{PYTHON}-windows-{ARCHES[arch][0]}-none"
    cache = work / "python"
    run("uv", "python", "install", key, "--install-dir", cache, "--no-bin", "--no-registry")
    backend = out / arch / "MarketPulse-backend"
    if backend.exists():
        shutil.rmtree(backend)
    python = backend / "python"
    shutil.copytree(cache / key, python)
    site = python / "Lib" / "site-packages"
    if site.exists():
        shutil.rmtree(site)
    site.mkdir(parents=True)
    requirements = work / "requirements.txt"
    run("uv", "export", "--locked", "--no-dev", "--no-emit-project", "--no-header", "-q", "-o", requirements, cwd=ROOT)
    common = ["--target", site, "--python-platform", ARCHES[arch][1], "--python-version", PYTHON]
    common += ["--only-binary", ":all:", "--no-deps"]
    run("uv", "pip", "install", *common, "--require-hashes", "-r", requirements)
    run("uv", "pip", "install", *common, wheel)
    # Entry-point executables generated by pip/uv embed the build interpreter's path.
    # The relative .cmd launcher and direct python.exe invocation replace them.
    for scripts in (site / "Scripts", site / "bin", python / "Scripts"):
        if scripts.exists():
            shutil.rmtree(scripts)
    (backend / "marketpulse.cmd").write_text(LAUNCHER, encoding="utf-8", newline="\r\n")
    return backend


def smoke_test(backend: Path) -> None:
    """Run a moved copy offline, outside the checkout, without the developer's Python."""
    with tempfile.TemporaryDirectory(prefix="marketpulse-windows-smoke-") as tmp:
        scratch = Path(tmp)
        moved = scratch / "Moved Apps" / "MarketPulse backend"
        shutil.copytree(backend, moved)
        env = {k: v for k, v in os.environ.items() if k.upper() in {"SYSTEMROOT", "WINDIR", "COMSPEC", "TEMP", "TMP"}}
        env.update(
            PATH=str(Path(os.environ["SYSTEMROOT"]) / "System32"),
            USERPROFILE=tmp,
            HOME=tmp,
            MARKETPULSE_DATA=str(scratch / "data"),
            MARKETPULSE_CONFIG=str(scratch / "config.toml"),
            PYTHONHOME=str(scratch / "not-python"),
            PYTHONPATH=str(scratch / "not-python"),
            NO_COLOR="1",
        )
        python = moved / "python" / "python.exe"

        def cli(*args: str) -> str:
            return run(
                python,
                "-I",
                "-B",
                "-X",
                "utf8",
                "-m",
                "marketpulse",
                *args,
                env=env,
                cwd=scratch,
                capture_output=True,
                text=True,
                encoding="utf-8",
            ).stdout

        if not cli("--version").strip().endswith(__version__):
            raise SystemExit("Bundled CLI version mismatch.")
        snapshot = json.loads(cli("desktop", "snapshot", "--demo"))
        if snapshot["backend"] != {"version": __version__, "python": PYTHON}:
            raise SystemExit(f"Unexpected backend: {snapshot['backend']}")
        note = "Fictional dépôt 東京 with spaces & punctuation!"
        cli("deposit", "--currency", "CAD", "--note", note, "--", "100")
        exported = cli("export")
        if "DEPOSIT" not in exported or note not in exported:
            raise SystemExit("Bundled CLI did not preserve the deposit and its note.")
        run(
            python,
            "-I",
            "-B",
            "-X",
            "utf8",
            "-c",
            "import curl_cffi, textual; from zoneinfo import ZoneInfo; ZoneInfo('America/Toronto')",
            env=env,
            cwd=scratch,
        )
        # Exercise the convenience launcher too. Native apps should use the argument-array
        # Python invocation above, avoiding cmd.exe's shell syntax for arbitrary user text.
        result = run(
            moved / "marketpulse.cmd",
            "--version",
            env=env,
            cwd=scratch,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        if not result.stdout.strip().endswith(__version__):
            raise SystemExit("Bundled .cmd launcher failed.")
        print("PASS: relocated Windows backend, demo snapshot, deposit/export, native imports, and launcher.")


def main() -> None:
    if sys.platform != "win32":
        raise SystemExit("Build the Windows backend on Windows.")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--arch", choices=sorted(ARCHES), default="x86_64")
    parser.add_argument("--out", type=Path, default=ROOT / "dist" / "windows")
    parser.add_argument("--skip-smoke", action="store_true", help="Skip runtime verification (not for CI).")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="marketpulse-windows-build-") as tmp:
        backend = build(args.arch, args.out.expanduser().resolve(), Path(tmp))
        if args.skip_smoke:
            print("Skipped runtime smoke test.")
        else:
            smoke_test(backend)
        print(f"{backend} (MarketPulse {__version__}, Python {PYTHON}, {args.arch})")


if __name__ == "__main__":
    main()
